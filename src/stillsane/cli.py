DEFAULT_CONFIG = "stillsane.yaml"

TARGET_STANZA = """\
# Generated by `stillsane init --from-logs`.
# The prompts below came from your logs. Point the target at your endpoint,
# uncomment the checks that apply, then run `stillsane baseline`.

targets:
  - name: prod
    type: openai_compatible
    base_url: https://api.openai.com/v1
    model: gpt-4o-mini
    api_key_env: OPENAI_API_KEY
    watch_fingerprint: true

"""

#: Exit codes in increasing order of severity. The codes themselves are chosen for
#: their meaning to CI (1 = the build should fail) rather than to be ordered, so
#: anything comparing two of them has to go through this.
_SEVERITY = (
    EXIT_CODES[Level.PASS],
    EXIT_CODES[Level.WARN],
    EXIT_CODES[Level.DRIFT],
    EXIT_CODES[Level.ERROR],
)

STARTER_CONFIG = """\
# stillsane -- drift canary for a deployed LLM app.
# Capture a baseline once, then run `stillsane check` on a schedule.

targets:
  - name: prod
    type: openai_compatible
    base_url: https://api.openai.com/v1
    model: gpt-4o-mini
    api_key_env: OPENAI_API_KEY   # the variable name, never the key itself
    watch_fingerprint: true

    # To monitor your own deployed app instead of a model API, use:
    #
    # - name: prod
    #   type: http
    #   base_url: https://your-app.example.com
    #   path: /api/chat
    #   body: {message: "{{prompt}}"}
    #   response_path: data.reply

probes:
  - id: example
    prompt: |
      Extract the total and due date from this invoice as JSON:
      Invoice #4471, dated 2026-06-01, due 30 days later. Total: 1240.50 USD.
    baseline_samples: 5   # paid once; this is where the variance band comes from
    check_samples: 3      # paid every run; only needs to locate a median
    checks:
      - valid_json
      - has_keys: [total, due_date]

# alerts:
#   webhook: https://example.com/hook
#   slack_webhook: https://hooks.slack.com/services/...
"""


def _load(path: str) -> Config:
    return load_config(path)


def _store(config: Config, config_path: str) -> tuple[BaselineStore, History]:
    root = Path(config_path).resolve().parent / config.state_dir
    return BaselineStore(root), History(root)


def cmd_init(args: argparse.Namespace) -> int:
    path = Path(args.config)
    if path.exists() and not args.force:
        print(f"{path} already exists. Use --force to overwrite.", file=sys.stderr)
        return 1

    if args.from_logs:
        return _init_from_logs(args, path)

    path.write_text(STARTER_CONFIG)
    print(f"Wrote {path}")
    print("\nNext:")
    print("  1. Edit it -- point `base_url` at your endpoint and write a real probe.")
    print("  2. stillsane baseline    # capture what 'normal' looks like")
    print("  3. stillsane check       # compare against it")
    return 0


def _init_from_logs(args: argparse.Namespace, path: Path) -> int:
    source = Path(args.from_logs)
    if not source.exists():
        print(f"stillsane: no such file or directory: {source}", file=sys.stderr)
        return EXIT_CODES[Level.ERROR]

    candidates = collect_candidates(read_records(source))
    if not candidates:
        print(
            f"stillsane: found no prompts in {source}.\n"
            "Expected JSONL, a JSON array, or a directory of .json files, where each "
            "record is an OpenAI-style request body (with `messages`) or has a "
            "`prompt` field.",
            file=sys.stderr,
        )
        return 1

    distinct = len(candidates)
    merged = cluster(candidates, default_embedder(args.embedder), args.merge_distance)

    header = TARGET_STANZA if not args.probes_only else ""
    path.write_text(header + to_yaml(merged, limit=args.limit))

    shown = min(len(merged), args.limit)
    print(f"Read {source}")
    print(f"  {distinct} distinct prompt(s), clustered into {len(merged)}")
    if shown < len(merged):
        print(f"  wrote the {shown} most frequent (use --limit to change)")
    print(f"\nWrote {path}")
    print("\nNext:")
    print("  1. Read it. These are your prompts, but the checks are commented out.")
    print("  2. Point `base_url` at your endpoint.")
    print("  3. stillsane baseline")
    return 0


def cmd_baseline(args: argparse.Namespace) -> int:
    config = _load(args.config)
    store, _ = _store(config, args.config)
    only = set(args.probe) if args.probe else None

    try:
        written = asyncio.run(capture_baseline(config, store, only=only))
    except RuntimeError as exc:
        print(f"stillsane: {exc}", file=sys.stderr)
        return EXIT_CODES[Level.ERROR]

    if not written:
        print("No probes matched.", file=sys.stderr)
        return 1

    for baseline in written:
        n = len(baseline.usable)
        print(
            f"  {baseline.probe_id} @ {baseline.target_name}: "
            f"v{baseline.version}, {n} sample(s)"
            + (f", fingerprint {baseline.fingerprint}" if baseline.fingerprint else "")
        )
    print(f"\nCaptured {len(written)} baseline(s). These will not change until you run this again.")

    # A floored band is a defaulted one: the samples showed no measurable spread,
    # so it fell back to the signal's absolute floor. Say so here, where the user
    # can still act, rather than letting them discover it via a surprising alert.
    floored = [(b, b.floored) for b in written if b.floored]
    if floored:
        print("\nBands that were defaulted rather than measured:")
        for baseline, names in floored:
            print(f"  {baseline.probe_id} @ {baseline.target_name}: {', '.join(names)}")
        print(
            "\nThese samples showed no measurable spread, so there was nothing to learn\n"
            "a band from and it fell back to a built-in floor. Either the probe really is\n"
            "that stable, which is fine, or it needs more samples to reveal its variation.\n"
            "Raise `baseline_samples` and recapture if you expect it to vary."
        )
    # The list above now covers pointwise signals too, but it still only says a band
    # was defaulted, not whether that will misreport. `bands` is where a floored band
    # that is also *wrong* gets named, along with its estimated false alarm rate.
    print("\nTo see every band and whether it holds:\n  stillsane bands")
    return 0


def cmd_bands(args: argparse.Namespace) -> int:
    """Show the bands a check would be judged against, and flag the broken ones.

    Reads only what is already on disk, so it costs nothing and needs no key.
    """
    config = _load(args.config)
    store, _ = _store(config, args.config)
    only = set(args.probe) if args.probe else None

    cfg = config.thresholds.to_band_config()
    reports = []
    missing = []

    for target in config.targets:
        for probe in config.probes:
            if only and probe.id not in only:
                continue
            if probe.targets and target.name not in probe.targets:
                continue
            baseline = store.load(target.name, probe.id)
            if baseline is None:
                missing.append(f"{probe.id} @ {target.name}")
                continue
            signals = build_probe_signals(probe.checks)
            reports.append(inspect_bands(baseline, signals, cfg, probe.check_samples))

    if not reports:
        if missing:
            print(
                "No baselines captured yet for: " + ", ".join(missing) + "\n"
                "Run `stillsane baseline` first.",
                file=sys.stderr,
            )
            return 1
        print("No probes matched.", file=sys.stderr)
        return 1

    if args.json:
        print(bands_as_json(reports))
    else:
        print(render_bands(reports, verbose=args.verbose))
    # stderr either way, so it cannot corrupt the JSON on stdout.
    if missing:
        print("\nNo baseline yet for: " + ", ".join(missing), file=sys.stderr)

    # Default is 0: inspecting a baseline should not break a build on its own. With
    # --strict it reports WARN, which is the honest level -- a suspect band is a
    # measurement problem, not evidence that anything drifted.
    if args.strict and any(p.suspect for p in reports):
        return EXIT_CODES[Level.WARN]
    return 0


def cmd_status(args: argparse.Namespace) -> int:
    """Report on the canary rather than on the model.

    Costs nothing and needs no key: it reads the history database only.
    """
    config = _load(args.config)
    _, history = _store(config, args.config)

    every = None
    if args.expect_every:
        try:
            every = parse_every(args.expect_every)
        except ValueError as exc:
            print(f"stillsane: {exc}", file=sys.stderr)
            return 1

    status = assess(
        history.recent(limit=args.limit),
        history.probe_results(limit_runs=args.limit),
        expect_every_s=every,
    )

    print(as_status_json(status) if args.json else render_status(status, limit=args.limit))

    # Default 0: asking whether the monitor is alive should not fail a build merely
    # for having been asked. --strict is for the cron job that wants to alert when
    # its own canary has stopped reporting, which is the whole point of the command.
    if args.strict and not status.healthy:
        return EXIT_CODES[Level.WARN]
    return 0


def cmd_calibrate(args: argparse.Namespace) -> int:
    """What the recorded clean runs say about the thresholds.

    Free and offline: the numbers were all written by past checks.
    """
    config = _load(args.config)
    _, history = _store(config, args.config)
    cfg = config.thresholds.to_band_config()
    only = set(args.probe) if args.probe else None

    rows = history.clean_z(limit_runs=args.limit)
    if only:
        known = {p.id for p in config.probes}
        typos = only - known
        if typos:
            print(f"No probes matched: {', '.join(sorted(typos))}", file=sys.stderr)
            return 1
        rows = [r for r in rows if r[0] in only]
        if not rows:
            print(
                f"No clean runs recorded yet for: {', '.join(sorted(only))}\n"
                "Run `stillsane check` on a schedule and come back.",
                file=sys.stderr,
            )
            return 1

    # `clean_runs`/`first`/`last` describe every clean run recorded, not just ones
    # touching the selected probe(s) -- a probe only appears in a run it was part
    # of, so narrowing this count as well would double-narrow and understate how
    # much evidence backs the report. It stays global context; the rows are scoped.
    clean_runs, first, last = history.clean_run_span()
    cal = assess_calibration(
        rows,
        clean_runs=clean_runs,
        warn_k=cfg.warn_k,
        drift_k=cfg.drift_k,
        first=first,
        last=last,
    )

    print(calibrate_as_json(cal) if args.json else render_calibration(cal))

    # --strict is for noticing that the thresholds have started firing on clean
    # runs, which is a real false-alarm rate rather than a tuning opinion.
    if args.strict and cal.false_alarms:
        return EXIT_CODES[Level.WARN]
    return 0


def cmd_history(args: argparse.Namespace) -> int:
    """Answer the question every alert provokes: since when?"""
    config = _load(args.config)
    _, history = _store(config, args.config)

    if args.signal and not (args.probe and args.target):
        # Without both, the query would quietly match nothing and read as "no
        # history" rather than "you did not say which probe".
        print(
            "--signal needs --probe and --target too, since the same signal is "
            "recorded for every probe.\nRun `stillsane history --signals` to see "
            "what is available.",
            file=sys.stderr,
        )
        return 1

    if args.signal:
        rows = history.signal_trend(args.probe, args.target, args.signal, limit=args.limit)
        if not rows:
            print(
                f"No history for {args.signal!r} on {args.probe!r} @ {args.target!r}.\n"
                "Run `stillsane check` at least once, or use `stillsane history --signals` "
                "to see what has been recorded.",
                file=sys.stderr,
            )
            return 1
        print(f"{args.signal}  {args.probe} @ {args.target}   (most recent first)")
        for when, observed, z in rows:
            value = f"{observed:.4g}" if observed is not None else "-"
            effect = f"z={z:+.1f}" if z is not None else ""
            print(f"  {when:<20} {value:>12}  {effect}")
        return 0

    if args.signals:
        recorded = history.recorded_signals()
        if not recorded:
            print("Nothing recorded yet. Run `stillsane check` first.", file=sys.stderr)
            return 1
        print("Recorded signals (pass any of these to --signal):")
        for probe, target, signal in recorded:
            print(f"  {signal:<24} {probe} @ {target}")
        return 0

    runs = history.recent(limit=args.limit)
    if not runs:
        print("No runs recorded yet. Run `stillsane check` first.", file=sys.stderr)
        return 1
    print(f"Last {len(runs)} run(s), most recent first:")
    for run_id, finished, level, _retries in runs:
        print(f"  {finished:<20}  {level:<6}  {run_id}")
    print("\nFor one signal over time:")
    print("  stillsane history --probe <id> --target <name> --signal semantic_distance")
    return 0


def _run_check(args: argparse.Namespace) -> int:
    config = _load(args.config)
    store, history = _store(config, args.config)
    only = set(args.probe) if args.probe else None

    result = asyncio.run(check(config, store, history, only=only))

    if args.json:
        print(as_json(result))
    else:
        print(render(result, verbose=args.verbose))

    if result.level is not Level.PASS:
        send(result, config.alerts.webhook, config.alerts.slack_webhook)
    return exit_code_for(result, config.alerts.fail_on_warn)


def cmd_check(args: argparse.Namespace) -> int:
    return _run_check(args)


def cmd_watch(args: argparse.Namespace) -> int:
    """Scheduled mode.

    A sleep loop, and honestly so. cron and GitHub Actions do this better -- they
    survive reboots, they log, and they alert when the job itself stops running,
    which a bare process cannot do for itself. This exists for laptops and quick
    trials; the docs point at a scheduler for anything real.
    """
    interval = args.interval
    print(f"Watching every {interval}s. Ctrl-C to stop.", file=sys.stderr)
    worst = 0
    try:
        while True:
            started = time.monotonic()
            code = _run_check(args)
            # Ranked by severity, not by numeric value. The exit codes are not
            # ordered -- DRIFT is 1 and WARN is 2 -- so `max()` on the raw numbers
            # would let a later warning mask an earlier drift in the summary.
            if _SEVERITY.index(code) > _SEVERITY.index(worst):
                worst = code
            if args.once:
                return code
            elapsed = time.monotonic() - started
            time.sleep(max(0.0, interval - elapsed))
    except KeyboardInterrupt:
        print("\nStopped.", file=sys.stderr)
        return worst


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="stillsane",
        description="Know when your LLM app quietly stops working.",
    )
    parser.add_argument("--version", action="version", version=f"stillsane {__version__}")
    parser.add_argument(
        "-c", "--config", default=DEFAULT_CONFIG, help=f"config file (default: {DEFAULT_CONFIG})"
    )
    sub = parser.add_subparsers(dest="command", required=True)

    p_init = sub.add_parser("init", help="write a starter config")
    p_init.add_argument("--force", action="store_true", help="overwrite an existing config")
    p_init.add_argument(
        "--from-logs",
        metavar="PATH",
        help="generate probes from a JSONL log, a JSON array, or a directory of .json files",
    )
    p_init.add_argument(
        "--limit", type=int, default=20, help="max probes to emit (default: 20)"
    )
    p_init.add_argument(
        "--merge-distance",
        type=float,
        default=DEFAULT_MERGE_DISTANCE,
        help=f"how aggressively to merge similar prompts (default: {DEFAULT_MERGE_DISTANCE})",
    )
    p_init.add_argument(
        "--embedder",
        choices=("model2vec", "hashing"),
        default="model2vec",
        help="embedder used to cluster prompts (default: model2vec)",
    )
    p_init.add_argument(
        "--probes-only",
        action="store_true",
        help="emit only the probes block, for pasting into an existing config",
    )
    p_init.set_defaults(func=cmd_init)

    p_base = sub.add_parser("baseline", help="capture a new baseline (explicit, never automatic)")
    p_base.add_argument("--probe", action="append", help="limit to this probe id (repeatable)")
    p_base.set_defaults(func=cmd_baseline)

    p_check = sub.add_parser("check", help="run once, compare, exit non-zero on drift")
    p_check.add_argument("--probe", action="append", help="limit to this probe id (repeatable)")
    p_check.add_argument("-v", "--verbose", action="store_true", help="show signals that passed")
    p_check.add_argument("--json", action="store_true", help="machine-readable output")
    p_check.set_defaults(func=cmd_check)

    p_bands = sub.add_parser("bands", help="show the learned bands and flag ones that will misreport")
    p_bands.add_argument("--probe", action="append", help="limit to this probe id (repeatable)")
    p_bands.add_argument(
        "-v", "--verbose", action="store_true", help="show every band, not only the suspect ones"
    )
    p_bands.add_argument(
        "--strict", action="store_true", help="exit 2 if any band will misreport"
    )
    p_bands.add_argument("--json", action="store_true", help="machine-readable output")
    p_bands.set_defaults(func=cmd_bands)

    p_status = sub.add_parser("status", help="is the canary itself alive and reporting?")
    p_status.add_argument(
        "--expect-every",
        metavar="INTERVAL",
        help="how often this is scheduled, e.g. 24h. Enables the overdue check.",
    )
    p_status.add_argument("--limit", type=int, default=20, help="runs to consider (default: 20)")
    p_status.add_argument("--strict", action="store_true", help="exit 2 if the canary is unhealthy")
    p_status.add_argument("--json", action="store_true", help="machine-readable output")
    p_status.set_defaults(func=cmd_status)

    p_cal = sub.add_parser(
        "calibrate", help="what your clean runs say about warn_k and drift_k"
    )
    p_cal.add_argument("--probe", action="append", help="limit to this probe id (repeatable)")
    p_cal.add_argument(
        "--limit", type=int, default=200, help="clean runs to consider (default: 200)"
    )
    p_cal.add_argument(
        "--strict", action="store_true", help="exit 2 if a threshold fires on clean runs"
    )
    p_cal.add_argument("--json", action="store_true", help="machine-readable output")
    p_cal.set_defaults(func=cmd_calibrate)

    p_hist = sub.add_parser("history", help="what past runs recorded, and when a signal moved")
    p_hist.add_argument("--probe", help="probe id (with --signal)")
    p_hist.add_argument("--target", help="target name (with --signal)")
    p_hist.add_argument("--signal", help="show this signal over time, e.g. semantic_distance")
    p_hist.add_argument(
        "--signals", action="store_true", help="list every signal that has recorded history"
    )
    p_hist.add_argument("--limit", type=int, default=20, help="rows to show (default: 20)")
    p_hist.set_defaults(func=cmd_history)

    p_watch = sub.add_parser("watch", help="scheduled mode (prefer cron or CI for anything real)")
    p_watch.add_argument("--probe", action="append", help="limit to this probe id (repeatable)")
    p_watch.add_argument("-v", "--verbose", action="store_true")
    p_watch.add_argument("--json", action="store_true")
    p_watch.add_argument(
        "--interval", type=float, default=3600.0, help="seconds between runs (default: 3600)"
    )
    p_watch.add_argument("--once", action="store_true", help="run a single iteration and exit")
    p_watch.set_defaults(func=cmd_watch)

    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        return args.func(args)
    except FileNotFoundError as exc:
        print(f"stillsane: {exc}", file=sys.stderr)
        return EXIT_CODES[Level.ERROR]
    except KeyboardInterrupt:
        return 130


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
